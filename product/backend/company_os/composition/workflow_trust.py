"""Supervisor-supplied consent and key inputs; no enrollment or key creation."""

from company_os.adapters.secrets.secret_adapter import read_secret_bytes
from company_os.bootstrap.consent_binding import verify_owner_installation_consent
from company_os.bootstrap.provisioning import ProvisioningBlocked


def check_workflow_trust(
    *,
    consent_path,
    consent_sha256,
    human_id,
    canonical_workspace,
    root_record,
    secret_directory_fd,
    secret_name,
    secret_owner_uid,
):
    # The pin, root and descriptor must come from the trusted supervisor, never
    # from the document being checked or a key generated by the trial itself.
    consent = verify_owner_installation_consent(
        consent_path,
        expected_human_id=human_id,
        expected_document_sha256=consent_sha256,
        expected_workspace=canonical_workspace,
        root_record=root_record,
    )
    if not consent.matched or consent.authority_granted:
        raise ProvisioningBlocked("CONSENT_CHECK_IS_NOT_ENROLLMENT")
    secret = read_secret_bytes(secret_directory_fd, secret_name, owner_uid=secret_owner_uid)
    return consent, secret
